function L(id, title, description, category, duration, extra) {
  return { id, day: id, title, description, category, duration, xp: 100, locked: id > 1, completed: false, ...extra }
}

function quiz(questions) {
  return { id: 'quiz', title: 'Тест', type: 'quiz', questions }
}

function theory(title, sections) {
  return { id: 'theory', title: 'Теория', type: 'theory', duration: 15, heading: title, sections }
}

function interactive(kind, title, payload) {
  return { id: 'interactive', title: title || 'Интерактивное объяснение', type: 'interactive', duration: 10, kind, ...payload }
}

function practice(kind, title, payload) {
  return { id: 'practice', title: title || 'Практика', type: 'practice', duration: 20, kind, ...payload }
}

