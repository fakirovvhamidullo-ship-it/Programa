export function pick(value, lang = 'ru') {
  if (value == null) return ''
  if (typeof value === 'string' || typeof value === 'number' || typeof value === 'boolean') return value
  if (Array.isArray(value)) return value.map((v) => pick(v, lang))
  if (typeof value === 'object' && ('ru' in value || 'en' in value || 'tg' in value)) {
    return value[lang] || value.ru || value.en || ''
  }
  return value
}

export function deepPick(node, lang = 'ru') {
  if (node == null) return node
  if (typeof node === 'string' || typeof node === 'number' || typeof node === 'boolean') return node
  if (Array.isArray(node)) return node.map((n) => deepPick(n, lang))
  if (typeof node === 'object' && ('ru' in node || 'en' in node || 'tg' in node) && !node.id && !node.type && !node.parts) {
    const keys = Object.keys(node)
    const onlyLang = keys.every((k) => k === 'ru' || k === 'en' || k === 'tg')
    if (onlyLang) return pick(node, lang)
  }
  if (typeof node === 'object') {
    const out = Array.isArray(node) ? [] : {}
    for (const [k, v] of Object.entries(node)) out[k] = deepPick(v, lang)
    return out
  }
  return node
}

